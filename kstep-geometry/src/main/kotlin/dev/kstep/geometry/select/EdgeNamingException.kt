package dev.kstep.geometry.select

import dev.kstep.geometry.GenerationSource

/**
 * Thrown when edges named by [dev.kstep.geometry.GenerationSource] cannot be resolved: a source has no image in
 * the generating feature (for example a vertex on the axis of a full revolve), a tracking step deleted or lost
 * the edge, the count differs from `expected`, or the source cannot be found in the profile. Never guesses.
 *
 * @property featureIndex position of the consuming feature, or null in the direct kernel API.
 * @property unresolved the sources without a usable image (or all sources when the count was wrong).
 * @property matched the edge indices that did resolve (indices of the shape the edges were requested on).
 * @property generatedCandidates description of each source to the images it has in the GENERATING shape.
 * @property candidates all regular edges of the affected shape (the message lists at most
 *   [EdgeSelection.MAX_LISTED_CANDIDATES]).
 */
class EdgeNamingException(
    message: String,
    val featureIndex: Int?,
    val unresolved: List<GenerationSource>,
    val matched: List<Int>,
    val generatedCandidates: Map<String, List<Int>>,
    val candidates: List<EdgeInfo>,
) : IllegalArgumentException(message) {
    internal companion object {
        /** Builds the message tail listing generated images and candidate edges (capped). */
        fun detail(
            generated: Map<String, List<Int>>,
            candidates: List<EdgeInfo>,
        ): String {
            val gen = generated.entries.take(EdgeSelection.MAX_LISTED_CANDIDATES)
            val genText = gen.joinToString("\n") { (name, images) -> "  generated by $name: $images" }
            val cand = candidates.filter { !it.degenerated }
            val shown =
                cand.take(EdgeSelection.MAX_LISTED_CANDIDATES).joinToString("\n") {
                    "  edge ${it.index}: ${it.kind} (${fmt(it.start.x)}, ${fmt(it.start.y)}, ${fmt(it.start.z)}) -> " +
                        "(${fmt(it.end.x)}, ${fmt(it.end.y)}, ${fmt(it.end.z)})"
                }
            val more =
                if (cand.size > EdgeSelection.MAX_LISTED_CANDIDATES) {
                    "\n  ... and ${cand.size - EdgeSelection.MAX_LISTED_CANDIDATES} more"
                } else {
                    ""
                }
            return (if (genText.isEmpty()) "" else genText + "\n") + "candidate edges:\n" + shown + more
        }

        private fun fmt(v: Double) = String.format(java.util.Locale.ROOT, "%.4g", v)
    }
}
